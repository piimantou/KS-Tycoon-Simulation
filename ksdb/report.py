"""REPORT.md: the Headline Indicators sheet, regenerated from the ledger."""
from __future__ import annotations

from .engine import headers, last_tick, read_ledger
from .store import Game, Ref, check, num, fmt


def _table(rows: list[dict], cols: list[str]) -> str:
    if not rows:
        return "_none_\n"
    def cell(r, c):
        v = r.get(c, "")
        try:
            return f"{float(v):,.2f}".rstrip("0").rstrip(".") if v != "" else ""
        except ValueError:
            return v
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(cell(r, c) for c in cols) + " |" for r in rows]
    return "\n".join(lines) + "\n"


def build(ref: Ref, game: Game) -> str:
    tick = last_tick(game)
    if not tick:
        return f"# {game.name}\n\nNo ticks resolved yet. Run `python -m ksdb advance {game.path.name}`.\n"
    hdr = headers(ref)
    at = lambda name: [r for r in read_ledger(game, name) if r["tick"] == tick]
    errors, gaps = check(ref, game)
    P = game.params
    out = [
        f"# {game.name} — {tick}\n",
        "Generated by `python -m ksdb report`; do not edit by hand.\n",
        f"Seed {game.seed} · promotions roll in months {game.promotion_months} · "
        f"upgrade mode `{P['upgrade_mode']}` · capital depreciation {fmt(P['capital_depreciation'])}/tick\n",
        "## Headline indicators (last 12 ticks)\n",
        _table(read_ledger(game, "indicators")[-12:], hdr["indicators"]),
        "Values are quantities × `foreign_price`; `balance_value` is supply − demand at those "
        "prices. No wage, tax, or budget figures exist yet.\n",
        "## Population\n", _table(at("population"), hdr["population"][1:]),
        "## Labour\n", _table(at("labour"), hdr["labour"][1:]),
        "## Buildings\n", _table(at("buildings"), hdr["buildings"][1:]),
        "### Levels\n", _table(at("building_levels"), hdr["building_levels"][1:]),
        "## Construction works\n", _table(at("construction"), hdr["construction"][1:]),
        "## Goods markets\n", _table(at("goods_market"), hdr["goods_market"][1:]),
        "## Bundle cost per worker (with dependents)\n",
    ]
    stock = {r["class"]: num(r["stock"]) for r in at("population")}
    cost = {}
    for r in at("consumption"):
        cost[r["class"]] = cost.get(r["class"], 0.0) + num(r["cost"])
    out.append(_table([{"class": c, "workers": stock[c],
                        "bundle_cost": cost.get(c, 0) / stock[c] if stock[c] else ""}
                       for c in ref.classes], ["class", "workers", "bundle_cost"]))
    out.append("Covers only demand groups mapped to goods.\n")
    out.append("## Warnings this tick\n")
    out.append("\n".join(f"- {r['message']}" for r in at("warnings")) or "_none_")
    out.append("\n## Data gaps\n")
    out.append("\n".join([f"- **error:** {e}" for e in errors] + [f"- {g}" for g in gaps]) or "_none_")
    return "\n".join(out) + "\n"
